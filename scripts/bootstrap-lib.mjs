import { randomBytes } from 'node:crypto';
import { chmodSync, constants, copyFileSync, existsSync, lstatSync, writeFileSync } from 'node:fs';

export const newSecret = () => randomBytes(32).toString('base64url');

export function validateValue(value) {
  if (/["\\\u0000-\u001f\u007f]/u.test(value)) {
    throw new Error('Use a single line without double quotes or backslashes. A generated password avoids these characters.');
  }
  return value;
}

export function email(value) {
  const result = value.trim().toLowerCase();
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(result) || /@example\.(com|org|invalid)$/i.test(result)) {
    throw new Error('Enter a real email address, such as your work email.');
  }
  return validateValue(result);
}

export function databaseUrl(value) {
  let url;
  try { url = new URL(value.trim()); } catch { throw new Error('Enter the complete PostgreSQL connection URL supplied by your database administrator.'); }
  if (!['postgres:', 'postgresql:'].includes(url.protocol) || !url.hostname || !url.username || url.pathname.length < 2 || url.pathname === '/ci') {
    throw new Error('Use a PostgreSQL URL with a host, username and database name. CI placeholder databases are not accepted.');
  }
  return validateValue(value.trim());
}

export function siteUrl(value, production) {
  let url;
  try { url = new URL(value.trim()); } catch { throw new Error('Enter a full URL, starting with https:// (or http://localhost for local use).'); }
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname);
  if (url.username || url.password || url.pathname !== '/' || url.search || url.hash ||
      (production ? url.protocol !== 'https:' || local : !local || !['http:', 'https:'].includes(url.protocol))) {
    throw new Error(production ? 'Use your public HTTPS address with no path, query or login details.' : 'Use a local origin such as http://localhost:3001, without a path.');
  }
  if (!production && url.port !== '3001') throw new Error('The local app uses port 3001. Enter http://localhost:3001.');
  return url.origin;
}

export function password(value) {
  validateValue(value);
  if (value.length < 16) throw new Error('Use at least 16 characters, or press Enter to generate a strong password.');
  return value;
}

export function serializeEnv(config) {
  return '# Generated by SHOP guided setup. Keep this file private; never commit or share it.\n' +
    Object.entries(config).map(([key, value]) => {
      if (!/^[A-Z][A-Z0-9_]*$/.test(key)) throw new Error('Invalid configuration key.');
      // Escape the escape character as well as expansion/quote characters.
      // Validation currently excludes quotes and backslashes, too.
      const encoded = validateValue(value).replace(/[\\$"]/g, (character) => `\\${character}`);
      return `${key}="${encoded}"`;
    }).join('\n') + '\n';
}

export function saveConfig(file, config, replace = false) {
  const contents = serializeEnv(config);
  let backup = null;
  if (existsSync(file)) {
    if (lstatSync(file).isSymbolicLink()) throw new Error('Configuration is a symbolic link. Ask its owner to update it; the installer will not follow it.');
    if (!replace) throw new Error('Existing configuration kept. Re-run the questionnaire to back up and replace it.');
    backup = `${file}.backup-${Date.now()}-${randomBytes(4).toString('hex')}`;
    copyFileSync(file, backup, constants.COPYFILE_EXCL);
    chmodSync(backup, 0o600);
  }
  // Serialize before touching the target so validation cannot truncate a working file.
  writeFileSync(file, contents, { flag: replace ? 'w' : 'wx', mode: 0o600 });
  chmodSync(file, 0o600);
  return backup;
}

export function redact(text, config) {
  const secrets = [config.AUTH_SECRET, config.ADMIN_PASSWORD, config.DATABASE_URL];
  try {
    const secret = new URL(config.DATABASE_URL).password;
    if (secret) secrets.push(secret, decodeURIComponent(secret));
  } catch { /* No configured database in preview mode. */ }
  let result = String(text);
  for (const secret of secrets.filter(Boolean).sort((a, b) => b.length - a.length)) {
    result = result.split(secret).join('[redacted]');
  }
  return result;
}

export function assertEmptyDatabase(tables) {
  if (tables.length) throw new Error('This database already contains tables. No migration was run. Use a new empty database or ask the database owner to follow docs/RELEASE.md.');
}

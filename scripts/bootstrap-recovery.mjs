import { createHash, randomBytes } from 'node:crypto';
import { existsSync, lstatSync, readFileSync, readdirSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseEnv } from 'node:util';
import { databaseUrl, email, password, siteUrl, validateValue } from './bootstrap-lib.mjs';

export const stateName = '.shop-setup-state.json';
const digest = (text) => createHash('sha256').update(text).digest('hex');

export function loadConfiguration(file) {
  if (!existsSync(file)) throw new Error('No configuration found. Run the setup questionnaire first.');
  if (lstatSync(file).isSymbolicLink()) throw new Error('Configuration is a symbolic link; ask its owner to manage it.');
  const text = readFileSync(file, 'utf8');
  if (!text.startsWith('# Generated by SHOP guided setup.')) {
    throw new Error('This configuration was not generated by guided setup. It has been kept unchanged. Use --reconfigure to back it up and configure guided setup.');
  }
  const config = Object.fromEntries(Object.entries(parseEnv(text)).map(([key, value]) => [key, validateValue(value.split('\\$').join('$'))]));
  const preview = config.ENABLE_STARTER_CATALOG === 'true';
  const production = !['localhost', '127.0.0.1', '[::1]'].includes(new URL(config.NEXTAUTH_URL).hostname);
  if (!config.AUTH_SECRET || config.AUTH_SECRET.length < 32) throw new Error('Configuration needs an authentication secret of at least 32 characters. Use --reconfigure.');
  siteUrl(config.NEXTAUTH_URL, production);
  if (preview) {
    if (config.DATABASE_URL || production) throw new Error('Preview configuration must use a local address and no database. Use --reconfigure.');
  } else {
    databaseUrl(config.DATABASE_URL);
    email(config.ADMIN_EMAIL);
    email(config.SHOP_CONTACT_EMAIL);
    password(config.ADMIN_PASSWORD);
  }
  return { config, mode: preview ? 'preview' : production ? 'production' : 'local' };
}

export function readRecovery(stateFile, envFile, mode) {
  const configHash = digest(readFileSync(envFile));
  if (existsSync(stateFile)) {
    if (lstatSync(stateFile).isSymbolicLink()) throw new Error('Setup state is a symbolic link; it was not changed.');
    let state;
    try { state = JSON.parse(readFileSync(stateFile, 'utf8')); } catch { throw new Error('Setup state is unreadable. Settings are safe; use --reconfigure to begin a new setup.'); }
    if (state.version !== 1) throw new Error('Unsupported setup state version. Settings were kept; use --reconfigure.');
    if (state.configHash === configHash && state.mode === mode) return state;
  }
  // Any settings change cancels old migration consent. Never silently migrate a new target.
  return newRecovery(envFile, mode);
}

export function newRecovery(envFile, mode) {
  return { version: 1, configHash: digest(readFileSync(envFile)), mode, migrateRequested: false, migrationAuthorized: false, migrationHash: null, completed: [], activeStep: null, status: 'incomplete' };
}

export function writeRecovery(file, state) {
  if (existsSync(file) && lstatSync(file).isSymbolicLink()) throw new Error('Setup state is a symbolic link; it was not changed.');
  const temporary = `${file}.${randomBytes(8).toString('hex')}.tmp`;
  try {
    writeFileSync(temporary, JSON.stringify(state, null, 2) + '\n', { flag: 'wx', mode: 0o600 });
    renameSync(temporary, file);
  } finally { if (existsSync(temporary)) unlinkSync(temporary); }
}

export async function step(file, state, name, operation) {
  state.activeStep = name;
  state.status = 'incomplete';
  writeRecovery(file, state);
  const result = await operation();
  state.completed = [...new Set([...state.completed, name])];
  state.activeStep = null;
  writeRecovery(file, state);
  return result;
}

export function migrationEvidence(root) {
  const directory = join(root, 'apps/web/prisma/migrations');
  const migrations = Object.fromEntries(readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))
    .map((entry) => [entry.name, digest(readFileSync(join(directory, entry.name, 'migration.sql')))]));
  const schema = readFileSync(join(root, 'apps/web/prisma/schema.prisma'), 'utf8');
  const objects = [...schema.matchAll(/^(?:model|enum)\s+(\w+)\s*\{/gm)].map((match) => match[1]);
  return { migrations, objects, hash: digest(JSON.stringify(migrations) + schema) };
}

export function checkMigrationRecovery(state, evidence, snapshot) {
  if (state.migrationHash && state.migrationHash !== evidence.hash) {
    throw new Error('Migration files changed since setup began. No migration was run. Follow docs/RELEASE.md before upgrading this database.');
  }
  if (!snapshot.objects.length) return;
  if (!state.migrationAuthorized || !snapshot.history?.length) {
    throw new Error('This database already contains objects without a matching setup checkpoint. No migration was run. Use a new empty database or the existing-database procedure in docs/RELEASE.md.');
  }
  if (snapshot.history.some((row) => !row.finished_at || row.rolled_back_at)) {
    throw new Error('A failed or interrupted SQL migration needs database-owner review. No automatic migration retry was attempted. See docs/RELEASE.md.');
  }
  if (snapshot.history.some((row) => evidence.migrations[row.migration_name] !== row.checksum) ||
      snapshot.objects.some((object) => object.schema_name !== 'public' || ![...evidence.objects, '_prisma_migrations'].includes(object.object_name))) {
    throw new Error('Database objects or migration history do not match this installation. No migration was run. Ask the database owner to review the schema.');
  }
}

export async function prepareDatabase({ state, evidence, inspect, deploy, persist }) {
  const snapshot = await inspect();
  checkMigrationRecovery(state, evidence, snapshot);
  state.migrationAuthorized = true;
  state.migrationHash = evidence.hash;
  // Persist consent before deploy. A crash after SQL commits can then recover safely.
  persist();
  await deploy();
  state.migrationApplied = true;
  persist();
}
